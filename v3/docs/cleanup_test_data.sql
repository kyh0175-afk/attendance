-- ═══════════════════════════════════════════════════════════════
--  스모크 테스트 데이터 정리
--  2026-08-01 P0 검증 중 만든 세션·출석 기록을 지운다.
--
--  ⚠️ 방학 중이라 이 날짜에 실제 출석은 없다는 전제.
--     반드시 섹션 1(미리보기)로 지울 대상을 눈으로 확인한 뒤 섹션 2를 실행할 것.
--     날짜를 바꿔 쓰려면 아래 v_day 값만 고치면 된다.
-- ═══════════════════════════════════════════════════════════════

-- ───────────────────────────────────────────────────────────────
-- 1. 미리보기 — 지워질 것들
-- ───────────────────────────────────────────────────────────────

-- 1-a. 대상 출석 기록
select id, "날짜", "원래시각", "퇴실시각", "학번", "이름", "프로그램", "장소", "세션id", "상태"
from public.attendance
where "날짜" = date '2026-08-01'
order by "원래시각";

-- 1-b. 대상 세션
select "세션id", "날짜", "프로그램", "장소", "교사", "활성", "입실코드", "퇴실코드"
from public.sessions
where "날짜" = date '2026-08-01'
order by "시작시각";

-- 1-c. 혹시 실제 데이터가 섞였는지 — 이 날짜의 학생 수가 1명(테스트 계정)인지 확인
select count(*) as "출석 행", count(distinct "학번") as "학생 수",
       string_agg(distinct "학번", ', ') as "학번들"
from public.attendance
where "날짜" = date '2026-08-01';


-- ───────────────────────────────────────────────────────────────
-- 2. 삭제 — 위 결과가 전부 테스트 기록임을 확인한 뒤에만 실행
-- ───────────────────────────────────────────────────────────────

begin;

delete from public.attendance
 where "날짜" = date '2026-08-01';

delete from public.sessions
 where "날짜" = date '2026-08-01';

-- 결과 확인 후 문제 없으면 commit, 이상하면 rollback
select (select count(*) from public.attendance where "날짜" = date '2026-08-01') as "남은 출석",
       (select count(*) from public.sessions   where "날짜" = date '2026-08-01') as "남은 세션";

commit;
-- rollback;   -- ← 되돌리려면 위 commit 대신 이 줄을 실행


-- ───────────────────────────────────────────────────────────────
-- 3. 최종 확인 — 열린 세션이 하나도 없어야 정상
-- ───────────────────────────────────────────────────────────────
select "세션id", "날짜", "장소", "프로그램", "입실코드"
from public.sessions
where "활성" = true
order by "날짜" desc;
